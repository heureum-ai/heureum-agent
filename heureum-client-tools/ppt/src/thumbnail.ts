function decodeJpeg(filePath: string): ImageData {
  const decoded = jpeg.decode(fs.readFileSync(filePath), { useTArray: true });
  return {
    width: decoded.width,
    height: decoded.height,
    data: decoded.data,
  };
}

function encodeJpeg(image: ImageData, filePath: string, quality = JPEG_QUALITY): void {
  const encoded = jpeg.encode(
    {
      width: image.width,
      height: image.height,
      data: image.data,
    },
    quality
  );
  fs.writeFileSync(filePath, encoded.data);
}

function createImage(width: number, height: number, color: [number, number, number]): ImageData {
  const data = new Uint8Array(width * height * 4);
  for (let i = 0; i < width * height; i++) {
    const idx = i * 4;
    data[idx] = color[0];
    data[idx + 1] = color[1];
    data[idx + 2] = color[2];
    data[idx + 3] = 255;
  }
  return { width, height, data };
}

function setPixel(image: ImageData, x: number, y: number, color: [number, number, number]): void {
  if (x < 0 || y < 0 || x >= image.width || y >= image.height) return;
  const idx = (y * image.width + x) * 4;
  image.data[idx] = color[0];
  image.data[idx + 1] = color[1];
  image.data[idx + 2] = color[2];
  image.data[idx + 3] = 255;
}

function drawLine(
  image: ImageData,
  x0: number,
  y0: number,
  x1: number,
  y1: number,
  color: [number, number, number],
  thickness = 1
): void {
  let startX = Math.round(x0);
  let startY = Math.round(y0);
  const endX = Math.round(x1);
  const endY = Math.round(y1);

  const dx = Math.abs(endX - startX);
  const sx = startX < endX ? 1 : -1;
  const dy = -Math.abs(endY - startY);
  const sy = startY < endY ? 1 : -1;
  let err = dx + dy;

  while (true) {
    for (let tx = -Math.floor(thickness / 2); tx <= Math.floor(thickness / 2); tx++) {
      for (let ty = -Math.floor(thickness / 2); ty <= Math.floor(thickness / 2); ty++) {
        setPixel(image, startX + tx, startY + ty, color);
      }
    }

    if (startX === endX && startY === endY) break;
    const e2 = 2 * err;
    if (e2 >= dy) {
      err += dy;
      startX += sx;
    }
    if (e2 <= dx) {
      err += dx;
      startY += sy;
    }
  }
}

